/**
 * Credentials `authorize` for Auth.js (src/auth.ts), extracted so it
 * can be tested against a real database.
 *
 * Security notes:
 *   - Returns `null` for EVERY failure mode (bad password, unknown
 *     email, deactivated account, no password set) — the caller can't
 *     tell which, so emails can't be enumerated.
 *   - Constant-time compare comes for free with argon2.verify.
 *   - `passwordHash === null` means "no credentials login" — reject
 *     without verifying against anything real.
 *   - Audit (src/lib/auth-events.ts): the admin-visible row records
 *     the real reason, but only for REAL accounts — failures for
 *     unknown emails write nothing, so bots can't flood the log.
 *   - Lockout: LOCKOUT_THRESHOLD failed sign-ins within
 *     LOCKOUT_WINDOW_MS (counting only failures since the last
 *     successful sign-in or admin unlock) refuse further attempts
 *     without checking the password, until the window passes.
 *     Counted from the audit rows — no extra schema. Refused
 *     attempts log as "sign_in_blocked", which doesn't count, so the
 *     lock lifts on schedule rather than sliding while an attacker
 *     keeps trying (and are throttled to one row a minute so they
 *     can't bury a user's history).
 *   - Atomic check-and-record: `reserveAttempt` takes a per-email
 *     Postgres advisory lock in a SHORT transaction, counts failures
 *     (in-flight attempts included), and inserts the failure row
 *     BEFORE the password is verified. The row is deleted on success
 *     and annotated with the reason on failure. Parallel guesses
 *     therefore can't all pass the check before any failure is
 *     written. A crash mid-verify leaves the row behind, which
 *     counts as a failure — fail closed. The lock is released
 *     before argon2 runs, so logins don't serialize on it.
 *   - Timing: unknown / inactive / passwordless / locked accounts
 *     burn one dummy argon2 verify so response time doesn't reveal
 *     whether an email has an account.
 *   - Availability trade-off (F129, ACCEPTED RISK — docs/DECISIONS.md
 *     ADR-020): the lock is per account, not per IP, so anyone who
 *     knows an email can hold that account locked by failing 5 times
 *     per window — including EVERY admin, who are also the people who
 *     could unlock. An IP factor is spoofable/shared and the
 *     alternative (no lock) exposes the password. Mitigations: an
 *     unlock by a team-directory manager (`sign_in_unlocked`, also
 *     written by a password reset) clears the count immediately —
 *     Admin-class targets need an Admin to do it; blocked-attempt
 *     rows are throttled; the lock lifts on its own after the window.
 *     Per-IP rate limiting belongs at the edge (Vercel Firewall rule
 *     on the sign-in route) and is the recommended real fix.
 *     BREAK-GLASS if every admin is locked out and no one can sign in
 *     to unlock: wait out the window (15 min), or insert the unlock
 *     row directly:
 *       INSERT INTO activity_logs (id, "userId", type, icon, source, title, timestamp)
 *       VALUES (gen_random_uuid()::text, '<user id>', 'auth', 'shield',
 *               'Security', 'Sign-in unlocked by an administrator', now());
 *     (`id` has no DB default — cuid is generated by Prisma — hence
 *     gen_random_uuid(); `title` must equal
 *     AUTH_EVENT_TITLES.sign_in_unlocked.)
 *   - Cost amplification (F411): locked / unknown-email attempts each
 *     burn one argon2 verify (~64 MiB, tens of ms of CPU), so login
 *     spam costs the server about what a real attempt does — one more
 *     reason to rate-limit at the edge.
 */

import { randomBytes } from "node:crypto";
import * as argon2 from "argon2";
import { z } from "zod";
import {
  AUTH_EVENT_TITLES,
  authEventDetail,
  logAuthEvent,
  type AuthEventKind,
} from "@/lib/auth-events";
import { prisma, type Tx } from "@/lib/prisma";

export const LOCKOUT_THRESHOLD = 5;
export const LOCKOUT_WINDOW_MS = 15 * 60 * 1000;
/** At most one "Blocked sign-in" audit row per account per this long. */
const BLOCKED_LOG_INTERVAL_MS = 60 * 1000;

type Db = Pick<Tx, "activityLog">;

// The pool is capped at 1 connection per process, so parallel
// attempts queue for the transaction; give them room (a queued
// attempt that still times out fails closed).
const TX_OPTIONS = { maxWait: 15_000, timeout: 15_000 };

/**
 * Failures of `failureKind` in the window, since the last event in
 * `resetKinds`. Counts in-flight reservations (see `reserveAttempt`).
 */
async function recentFailures(
  db: Db,
  userId: string,
  failureKind: AuthEventKind,
  resetKinds: AuthEventKind[]
): Promise<number> {
  const windowStart = new Date(Date.now() - LOCKOUT_WINDOW_MS);
  const lastReset = await db.activityLog.findFirst({
    where: {
      userId,
      type: "auth",
      title: { in: resetKinds.map((k) => AUTH_EVENT_TITLES[k]) },
      timestamp: { gt: windowStart },
    },
    orderBy: { timestamp: "desc" },
    select: { timestamp: true },
  });
  return db.activityLog.count({
    where: {
      userId,
      type: "auth",
      title: AUTH_EVENT_TITLES[failureKind],
      timestamp: { gt: lastReset?.timestamp ?? windowStart },
    },
  });
}

const SIGN_IN_RESETS: AuthEventKind[] = ["sign_in", "sign_in_unlocked"];

/** Failed sign-ins in the window, since the last successful one. */
export async function isLockedOut(
  userId: string,
  db: Db = prisma
): Promise<boolean> {
  return (
    (await recentFailures(db, userId, "sign_in_failed", SIGN_IN_RESETS)) >=
    LOCKOUT_THRESHOLD
  );
}

/**
 * Atomically check the throttle and record the attempt BEFORE the
 * secret is verified. Serialised per `lockKey` with a transaction-
 * scoped Postgres advisory lock, held only for the count + insert
 * (never across argon2). The inserted row is a failure row (so
 * in-flight parallel attempts count toward the threshold) that the
 * caller settles with `settleAttempt`.
 */
export async function reserveAttempt(opts: {
  userId: string;
  /** Normalised key the lock serialises on (e.g. the email). */
  lockKey: string;
  failureKind: "sign_in_failed" | "password_change_failed";
  resetKinds: AuthEventKind[];
}): Promise<{ locked: true } | { locked: false; reservationId: string }> {
  const detail = await authEventDetail("attempt did not complete");
  return prisma.$transaction(async (tx) => {
    await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${opts.lockKey}))`;
    const failures = await recentFailures(
      tx,
      opts.userId,
      opts.failureKind,
      opts.resetKinds
    );
    if (failures >= LOCKOUT_THRESHOLD) return { locked: true as const };
    const row = await tx.activityLog.create({
      data: {
        matterId: null,
        userId: opts.userId,
        type: "auth",
        icon: "shield",
        source: "Security",
        title: AUTH_EVENT_TITLES[opts.failureKind],
        detail,
      },
      select: { id: true },
    });
    return { locked: false as const, reservationId: row.id };
  }, TX_OPTIONS);
}

/** Settle a reservation: success removes it (the caller logs the
 *  success event), failure annotates it with the real reason. A
 *  settle that fails leaves the reservation as a counted failure. */
export async function settleAttempt(
  reservationId: string,
  outcome: { ok: true } | { ok: false; reason: string }
): Promise<void> {
  try {
    if (outcome.ok) {
      await prisma.activityLog.delete({ where: { id: reservationId } });
    } else {
      await prisma.activityLog.update({
        where: { id: reservationId },
        data: { detail: await authEventDetail(outcome.reason) },
      });
    }
  } catch (err) {
    console.warn("[auth-events] failed to settle attempt", err);
  }
}

// A real argon2id hash with the same parameters as stored ones,
// computed once, so "no such account" costs the same as "wrong
// password".
let dummyHash: Promise<string> | undefined;
async function burnVerify(password: string): Promise<void> {
  dummyHash ??= argon2.hash(randomBytes(16).toString("hex"), {
    type: argon2.argon2id,
  });
  try {
    await argon2.verify(await dummyHash, password);
  } catch {
    // Timing equaliser only — the result is irrelevant. Drop a
    // cached rejection so the next call retries the hash instead of
    // silently skipping the burn forever.
    dummyHash = undefined;
  }
}

/** One "Blocked sign-in" row per account per minute. */
async function logBlockedThrottled(userId: string): Promise<void> {
  const recent = await prisma.activityLog.findFirst({
    where: {
      userId,
      type: "auth",
      title: AUTH_EVENT_TITLES.sign_in_blocked,
      timestamp: { gt: new Date(Date.now() - BLOCKED_LOG_INTERVAL_MS) },
    },
    select: { id: true },
  });
  if (!recent) await logAuthEvent({ userId, kind: "sign_in_blocked" });
}

const credentialsSchema = z.object({
  email: z.string().trim().toLowerCase().email(),
  password: z.string().min(1),
});

export async function authorizeCredentials(raw: unknown) {
  // Auth.js hands us `Partial<Record<...>>` from the form — validate
  // shape before trusting it.
  const parsed = credentialsSchema.safeParse(raw);
  if (!parsed.success) return null;

  const user = await prisma.user.findUnique({
    where: { email: parsed.data.email },
    select: {
      id: true,
      email: true,
      name: true,
      image: true,
      passwordHash: true,
      isActive: true,
    },
  });
  if (!user) {
    await burnVerify(parsed.data.password);
    return null;
  }
  if (!user.isActive || !user.passwordHash) {
    await burnVerify(parsed.data.password);
    await logAuthEvent({
      userId: user.id,
      kind: "sign_in_failed",
      reason: !user.isActive ? "account deactivated" : "no password set",
    });
    return null;
  }

  // Check-and-record in one atomic step (see header). A DB error
  // here throws → Auth.js rejects the sign-in: fail closed.
  const attempt = await reserveAttempt({
    userId: user.id,
    lockKey: `sign_in:${parsed.data.email}`,
    failureKind: "sign_in_failed",
    resetKinds: SIGN_IN_RESETS,
  });
  if (attempt.locked) {
    await burnVerify(parsed.data.password);
    await logBlockedThrottled(user.id);
    return null;
  }

  const ok = await argon2.verify(user.passwordHash, parsed.data.password);
  if (!ok) {
    await settleAttempt(attempt.reservationId, {
      ok: false,
      reason: "wrong password",
    });
    return null;
  }
  await settleAttempt(attempt.reservationId, { ok: true });
  await logAuthEvent({ userId: user.id, kind: "sign_in" });

  // The shape returned here lands in the `jwt` callback as the `user`
  // arg on first sign-in. Only forward what the session needs.
  return { id: user.id, email: user.email, name: user.name, image: user.image };
}
